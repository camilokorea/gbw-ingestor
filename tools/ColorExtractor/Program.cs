using ColorExtractor;
using eBird.Ingestor.Infrastructure;
using Microsoft.EntityFrameworkCore;
using Microsoft.Extensions.Configuration;
using Microsoft.Extensions.DependencyInjection;
using Microsoft.Extensions.Hosting;
using Microsoft.Extensions.Logging;
using SixLabors.ImageSharp;
using SixLabors.ImageSharp.PixelFormats;

const int MaxPixelSamples = 3000;  // sample per image for fast K-means on 8k+ images
const int SqlBatchSize = 100;       // VALUES rows per INSERT statement

// ── Bootstrap ────────────────────────────────────────────────────────────────

var host = Host.CreateDefaultBuilder(args)
    .ConfigureAppConfiguration((_, config) =>
    {
        config.SetBasePath(AppContext.BaseDirectory);
        config.AddJsonFile("appsettings.json", optional: false);
        config.AddCommandLine(args);
    })
    .ConfigureServices((context, services) =>
    {
        services.AddInfrastructure(context.Configuration);
    })
    .Build();

var config = host.Services.GetRequiredService<IConfiguration>();
var logger = host.Services.GetRequiredService<ILogger<Program>>();
var db = host.Services.GetRequiredService<eBird.Ingestor.Infrastructure.Data.EbirdIngestorDbContext>();

var imageFolder = config["ColorExtractor:ImageFolder"]
    ?? throw new InvalidOperationException("ColorExtractor:ImageFolder is not configured.");
var numColors = int.Parse(config["ColorExtractor:NumColors"] ?? "10");
var outputFile = config["ColorExtractor:OutputFile"] ?? "SpeciesColorSeed.sql";

if (!Directory.Exists(imageFolder))
    throw new DirectoryNotFoundException($"Image folder not found: {imageFolder}");

logger.LogInformation("Loading species dictionary from database...");

// Build O(1) lookup: lowercase scientific name → species id
// GroupBy handles any duplicate ScientificName entries in the DB (keeps first)
var speciesDict = (await db.Species
    .AsNoTracking()
    .Select(s => new { s.Id, SciName = s.ScientificName.ToLower() })
    .ToListAsync())
    .GroupBy(s => s.SciName)
    .ToDictionary(g => g.Key, g => g.First().Id);

logger.LogInformation("Loaded {Count} species.", speciesDict.Count);

var imageFiles = Directory.GetFiles(imageFolder, "*.jpg");
logger.LogInformation("Found {Count} image files to process.", imageFiles.Length);

var sqlLines = new List<string>
{
    "-- SpeciesColor seed data generated by ColorExtractor tool",
    $"-- Generated: {DateTime.UtcNow:yyyy-MM-dd HH:mm:ss} UTC",
    $"-- Images processed: {imageFiles.Length}, Colors per species: {numColors}",
    $"-- Pixel sample per image: {MaxPixelSamples}",
    "",
    "SET IDENTITY_INSERT [SpeciesColors] ON;",
    "",
};

// Accumulate all value rows for batched INSERT
var allValueRows = new List<string>();

int id = 1;
int matched = 0;
int skipped = 0;

foreach (var filePath in imageFiles.OrderBy(f => f))
{
    var fileName = Path.GetFileNameWithoutExtension(filePath);
    var parts = fileName.Split('-');

    if (parts.Length < 2)
    {
        logger.LogWarning("Cannot parse filename: {File}", fileName);
        skipped++;
        continue;
    }

    // Scientific name = last 2 hyphenated parts → "genus species" (Title Case)
    var genus = Capitalize(parts[^2]);
    var species = Capitalize(parts[^1]);
    var sciName = $"{genus} {species}".ToLower();

    if (!speciesDict.TryGetValue(sciName, out var speciesId))
    {
        logger.LogWarning("No DB match for scientific name: '{SciName}' (file: {File})", $"{genus} {species}", fileName);
        skipped++;
        continue;
    }

    logger.LogInformation("Processing [{SciName}] → SpeciesId={Id}", $"{genus} {species}", speciesId);

    List<(byte R, byte G, byte B, double Pct)> colors;
    try
    {
        colors = ExtractColors(filePath, numColors);
    }
    catch (Exception ex)
    {
        logger.LogError("Failed to process {File}: {Msg}", fileName, ex.Message);
        skipped++;
        continue;
    }

    for (int rank = 0; rank < colors.Count; rank++)
    {
        var (r, g, b, pct) = colors[rank];
        var hex = $"#{r:X2}{g:X2}{b:X2}";
        allValueRows.Add($"({id},{speciesId},{rank + 1},'{hex}',{r},{g},{b},{pct:F2})");
        id++;
    }
    matched++;
}

// Write batched INSERT statements
var header = "INSERT INTO [SpeciesColors] ([Id],[SpeciesId],[Rank],[HexColor],[R],[G],[B],[CoveragePercent]) VALUES";
for (int i = 0; i < allValueRows.Count; i += SqlBatchSize)
{
    var batch = allValueRows.Skip(i).Take(SqlBatchSize);
    sqlLines.Add(header);
    sqlLines.Add(string.Join("," + Environment.NewLine, batch) + ";");
    sqlLines.Add("");
}

sqlLines.Add("SET IDENTITY_INSERT [SpeciesColors] OFF;");
sqlLines.Add("");
sqlLines.Add($"-- Total: {matched} species seeded, {skipped} skipped (no DB match or parse error).");
sqlLines.Add($"-- Total rows: {allValueRows.Count}");

await File.WriteAllLinesAsync(outputFile, sqlLines);

logger.LogInformation("Done. {Matched} species seeded, {Skipped} skipped.", matched, skipped);
logger.LogInformation("Output written to: {File}", Path.GetFullPath(outputFile));

// ── K-means Color Extraction ──────────────────────────────────────────────────

static List<(byte R, byte G, byte B, double Pct)> ExtractColors(string filePath, int k)
{
    using var image = Image.Load<Rgba32>(filePath);

    // Collect non-background pixels (skip near-white and transparent)
    var allPixels = new List<(byte R, byte G, byte B)>(image.Width * image.Height / 4);

    image.ProcessPixelRows(accessor =>
    {
        for (int y = 0; y < accessor.Height; y++)
        {
            var row = accessor.GetRowSpan(y);
            for (int x = 0; x < row.Length; x++)
            {
                ref Rgba32 px = ref row[x];
                if (px.A < 30) continue;                               // transparent
                if (px.R > 240 && px.G > 240 && px.B > 240) continue; // near-white background
                allPixels.Add((px.R, px.G, px.B));
            }
        }
    });

    // Sample for performance — 3000 pixels is more than enough for accurate clustering
    List<(byte R, byte G, byte B)> pixels;
    if (allPixels.Count > MaxPixelSamples)
    {
        var step = allPixels.Count / MaxPixelSamples;
        pixels = Enumerable.Range(0, MaxPixelSamples)
            .Select(i => allPixels[i * step])
            .ToList();
    }
    else
    {
        pixels = allPixels;
    }

    if (pixels.Count < k)
        k = Math.Max(1, pixels.Count);

    var centroids = KMeans.Cluster(pixels, k, maxIterations: 25);

    return centroids
        .OrderByDescending(c => c.Pct)
        .Take(k)
        .ToList();
}

static string Capitalize(string s) =>
    s.Length == 0 ? s : char.ToUpper(s[0]) + s[1..].ToLower();
